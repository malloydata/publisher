// Generates a Malloy package of configurable size for the perf harness: N model
// files of M sources each (joins, dimensions, measures, views), a shared base
// model, an `index.malloy` surface, two reports, and deterministic local
// Parquet data written by DuckDB. Runs under Bun, never under k6.
//
//   bun perf/gen-package.ts <out-dir> [--preset small|medium|large] [--rows N] [--seed S]
//
// The data is a pure function of (rows, seed): every value is derived from
// DuckDB's `hash()` of the row number and the seed, so two runs with the same
// arguments write the same rows. Nothing here is meant to be committed; the
// runner generates into a temp dir and deletes it afterwards.

import { DuckDBInstance } from "@duckdb/node-api";
import { mkdirSync, readdirSync, statSync, writeFileSync } from "fs";
import path from "path";

export interface PackageShape {
   /** Model files, `model_01.malloy` … */
   models: number;
   /** Fact sources per model file. */
   sourcesPerModel: number;
   /** Extra generated dimensions per source (beyond the fixed ones). */
   dimensions: number;
   /** Extra generated measures per source (beyond the fixed ones). */
   measures: number;
   /** Extra generated views per source (beyond the fixed four). */
   views: number;
}

export const PRESETS: Record<string, PackageShape> = {
   small: {
      models: 2,
      sourcesPerModel: 2,
      dimensions: 8,
      measures: 8,
      views: 4,
   },
   medium: {
      models: 8,
      sourcesPerModel: 4,
      dimensions: 16,
      measures: 12,
      views: 6,
   },
   large: {
      models: 24,
      sourcesPerModel: 6,
      dimensions: 24,
      measures: 16,
      views: 8,
   },
};

export const DEFAULT_ROWS = 1_000_000;
export const DEFAULT_SEED = 42;

export interface GeneratedPackage {
   dir: string;
   preset: string;
   shape: PackageShape;
   rows: number;
   seed: number;
   modelFiles: number;
   sources: number;
   malloyBytes: number;
   dataBytes: number;
   /** Exported fact sources, `sales_<m>_<s>`, in model order. */
   exportedSources: string[];
   reports: string[];
}

const HEADER = "// Generated by k6-tests/perf/gen-package.ts. Do not edit.\n";

const pad = (n: number): string => String(n).padStart(2, "0");
export const sourceName = (m: number, s: number): string => `sales_${m}_${s}`;

/** Deterministic integer in [0, mod) for row `col`, salt `k`. */
const h = (col: string, k: number, mod: number, seed: number): string =>
   `(hash(${col} * 1000003 + ${seed * 7919 + k}) % ${mod})`;

async function writeData(
   dataDir: string,
   rows: number,
   seed: number,
): Promise<void> {
   mkdirSync(dataDir, { recursive: true });
   const customers = Math.max(1000, Math.floor(rows / 50));
   const products = 2000;
   const stores = 200;
   const q = (p: string): string => `'${path.join(dataDir, p)}'`;
   const states = [
      "CA",
      "NY",
      "TX",
      "FL",
      "WA",
      "IL",
      "PA",
      "OH",
      "GA",
      "NC",
      "MI",
      "NJ",
      "VA",
      "AZ",
      "MA",
      "CO",
   ];
   const stateList = `[${states.map((s) => `'${s}'`).join(",")}]`;
   const statements = [
      `COPY (SELECT
          i AS id,
          i // 3 AS order_id,
          ${h("i", 1, customers, seed)}::BIGINT AS customer_id,
          ${h("i", 2, products, seed)}::BIGINT AS product_id,
          ${h("i", 3, stores, seed)}::BIGINT AS store_id,
          DATE '2022-01-01' + ${h("i", 4, 1095, seed)}::INTEGER AS order_date,
          (1 + ${h("i", 5, 5, seed)})::INTEGER AS quantity,
          (5 + ${h("i", 6, 20000, seed)} / 100.0)::DOUBLE AS unit_price,
          (${h("i", 7, 30, seed)} / 100.0)::DOUBLE AS discount,
          ['Complete','Shipped','Returned','Cancelled'][1 + ${h("i", 8, 4, seed)}::INTEGER] AS status,
          ['web','store','mobile'][1 + ${h("i", 9, 3, seed)}::INTEGER] AS channel
        FROM range(${rows}) t(i)) TO ${q("fact.parquet")} (FORMAT parquet)`,
      `COPY (SELECT
          i AS customer_id,
          'Customer ' || i AS full_name,
          ['Consumer','Corporate','Home Office','Small Business'][1 + ${h("i", 11, 4, seed)}::INTEGER] AS segment,
          ${stateList}[1 + ${h("i", 12, states.length, seed)}::INTEGER] AS state,
          (18 + ${h("i", 13, 60, seed)})::INTEGER AS age,
          DATE '2018-01-01' + ${h("i", 14, 1800, seed)}::INTEGER AS signup_date
        FROM range(${customers}) t(i)) TO ${q("customers.parquet")} (FORMAT parquet)`,
      `COPY (SELECT
          i AS product_id,
          'Product ' || i AS name,
          'Category ' || ${h("i", 21, 20, seed)} AS category,
          'Brand ' || ${h("i", 22, 100, seed)} AS brand,
          (2 + ${h("i", 23, 10000, seed)} / 100.0)::DOUBLE AS cost
        FROM range(${products}) t(i)) TO ${q("products.parquet")} (FORMAT parquet)`,
      `COPY (SELECT
          i AS store_id,
          'Store ' || i AS name,
          'Region ' || ${h("i", 31, 8, seed)} AS region,
          ${stateList}[1 + ${h("i", 32, states.length, seed)}::INTEGER] AS state
        FROM range(${stores}) t(i)) TO ${q("stores.parquet")} (FORMAT parquet)`,
   ];
   const instance = await DuckDBInstance.create(":memory:");
   const conn = await instance.connect();
   try {
      for (const sql of statements) await conn.run(sql);
   } finally {
      conn.closeSync();
      instance.closeSync();
   }
}

function baseModel(): string {
   return `${HEADER}
#(doc) Customers, one row per customer
source: customers is duckdb.table('data/customers.parquet') extend {
  primary_key: customer_id
  measure: customer_count is count()
}

#(doc) Products, one row per product
source: products is duckdb.table('data/products.parquet') extend {
  primary_key: product_id
  measure: product_count is count()
}

#(doc) Stores, one row per store
source: stores is duckdb.table('data/stores.parquet') extend {
  primary_key: store_id
  measure: store_count is count()
}
`;
}

// Expressions the generated fields cycle through, so sources are not all
// textually identical (and so compile work grows with the field count).
const DIM_EXPRS = [
   (i: number) => `quantity * ${i + 1}`,
   (i: number) => `unit_price * ${1 + i / 10}`,
   (i: number) => `concat(status, '-${i}')`,
   (i: number) => `order_date + ${i} days`,
   (i: number) =>
      `pick 'high' when unit_price > ${50 + i * 5} pick 'mid' when unit_price > ${20 + i} else 'low'`,
   (i: number) => `concat(customers.segment, ' / ', channel, ' ${i}')`,
   (i: number) => `products.cost * ${i + 1}`,
   (i: number) => `concat(stores.region, ':${i}')`,
];
const MEASURE_EXPRS = [
   (i: number) => `sum(quantity * unit_price * ${1 + i / 100})`,
   (i: number) => `avg(unit_price + ${i})`,
   (i: number) => `count() { where: quantity > ${i % 5} }`,
   (i: number) => `max(discount * ${i + 1})`,
   (i: number) => `products.cost.sum() * ${i + 1}`,
   (i: number) => `count(customer_id) { where: discount < ${(i % 30) / 100} }`,
];

function factSource(m: number, s: number, shape: PackageShape): string {
   const name = sourceName(m, s);
   const dims: string[] = [];
   for (let i = 0; i < shape.dimensions; i++) {
      dims.push(`    d_${i} is ${DIM_EXPRS[i % DIM_EXPRS.length]!(i)}`);
   }
   const measures: string[] = [];
   for (let i = 0; i < shape.measures; i++) {
      measures.push(
         `    m_${i} is ${MEASURE_EXPRS[i % MEASURE_EXPRS.length]!(i)}`,
      );
   }
   const views: string[] = [];
   for (let i = 0; i < shape.views; i++) {
      const dim = `d_${i % Math.max(1, shape.dimensions)}`;
      const mea = `m_${i % Math.max(1, shape.measures)}`;
      views.push(`  view: v_${i} is {
    group_by: ${shape.dimensions > 0 ? dim : "status"}
    aggregate: revenue${shape.measures > 0 ? `, ${mea}` : ""}
    limit: 20
  }`);
   }
   return `
#(doc) Order lines for model ${m}, source ${s}
source: ${name} is duckdb.table('data/fact.parquet') extend {
  primary_key: id

  join_one:
    customers with customer_id
    products with product_id
    stores with store_id

  dimension:
    order_month is order_date.month
    order_year is order_date.year
    line_total is quantity * unit_price * (1 - discount)
    category is products.category
    brand is products.brand
    region is stores.region
    segment is customers.segment
${dims.join("\n")}

  measure:
    row_count is count()
    order_count is count(order_id)
    revenue is line_total.sum()
    gross_margin is sum(line_total - quantity * products.cost)
    customer_count is customers.count()
    avg_order_value is revenue / nullif(order_count, 0)
${measures.join("\n")}

  #(doc) A handful of headline figures (cheap: one scan, no joins)
  view: kpis is {
    aggregate: row_count, order_count
  }

  #(doc) Monthly revenue by status (a group-by over the fact table)
  view: by_month_status is {
    group_by: order_month, status
    aggregate: revenue, order_count
    order_by: order_month desc
    limit: 500
  }

  #(doc) Revenue by category and region (two joins)
  view: by_category_region is {
    group_by: category, region
    aggregate: revenue, gross_margin, customer_count
    order_by: revenue desc
  }

  #(doc) Nested overview: every join, three nests
  view: overview is {
    group_by: region
    aggregate: revenue, gross_margin, order_count, customer_count
    nest: by_segment is {
      group_by: segment
      aggregate: revenue, avg_order_value
    }
    nest: top_categories is {
      group_by: category
      aggregate: revenue
      limit: 5
    }
    nest: by_year is {
      group_by: order_year
      aggregate: revenue, gross_margin
    }
  }

${views.join("\n\n")}
}
`;
}

function modelFile(m: number, shape: PackageShape): string {
   const parts = [
      HEADER,
      `import { customers, products, stores } from "base.malloy"\n`,
   ];
   for (let s = 1; s <= shape.sourcesPerModel; s++) {
      parts.push(factSource(m, s, shape));
   }
   return parts.join("\n");
}

function indexModel(shape: PackageShape): string {
   const imports: string[] = [];
   const exported: string[] = [];
   for (let m = 1; m <= shape.models; m++) {
      const names: string[] = [];
      for (let s = 1; s <= shape.sourcesPerModel; s++) {
         names.push(sourceName(m, s));
      }
      imports.push(
         `import { ${names.join(", ")} } from "model_${pad(m)}.malloy"`,
      );
      exported.push(...names);
   }
   return `${HEADER}
// The package surface: every fact source is published; the base dimension
// sources (customers, products, stores) are building blocks only.
${imports.join("\n")}

export { ${exported.join(", ")} }
`;
}

function gridReport(first: string): string {
   return `${HEADER}##! experimental.givens
##" A generated grid report over ${first}.
## artifact { layout=grid title="Generated overview" tiles=["${first} -> kpis", "${first} -> by_month_status", "${first} -> by_category_region", "${first} -> overview"] } dashboard { columns=12 }
import { ${first} } from "model_01.malloy"
`;
}

function linearReport(first: string, second: string): string {
   return `${HEADER}##! experimental.givens
##" A generated linear report reading two sources top to bottom.
## artifact { layout=linear title="Generated story" tiles=["${first} -> kpis", "${first} -> by_category_region", "${second} -> by_month_status"] }
import { ${first}, ${second} } from "model_01.malloy"
`;
}

function dirBytes(dir: string): number {
   let total = 0;
   for (const entry of readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, entry.name);
      total += entry.isDirectory() ? dirBytes(full) : statSync(full).size;
   }
   return total;
}

export async function generatePackage(opts: {
   dir: string;
   preset: string;
   rows?: number;
   seed?: number;
   name?: string;
   /** Reuse Parquet already written here instead of generating it. */
   dataFrom?: string;
}): Promise<GeneratedPackage> {
   const shape = PRESETS[opts.preset];
   if (!shape) {
      throw new Error(
         `unknown preset "${opts.preset}" (expected ${Object.keys(PRESETS).join(", ")})`,
      );
   }
   const rows = opts.rows ?? DEFAULT_ROWS;
   const seed = opts.seed ?? DEFAULT_SEED;
   mkdirSync(opts.dir, { recursive: true });

   const name = opts.name ?? `gen-${opts.preset}`;
   writeFileSync(
      path.join(opts.dir, "publisher.json"),
      JSON.stringify(
         {
            name,
            version: "1.0.0",
            description: `Generated perf package: preset ${opts.preset}, ${rows} fact rows, seed ${seed}`,
         },
         null,
         2,
      ) + "\n",
   );
   writeFileSync(path.join(opts.dir, "base.malloy"), baseModel());
   for (let m = 1; m <= shape.models; m++) {
      writeFileSync(
         path.join(opts.dir, `model_${pad(m)}.malloy`),
         modelFile(m, shape),
      );
   }
   writeFileSync(path.join(opts.dir, "index.malloy"), indexModel(shape));
   const first = sourceName(1, 1);
   const second = sourceName(1, Math.min(2, shape.sourcesPerModel));
   writeFileSync(path.join(opts.dir, "overview.malloy"), gridReport(first));
   writeFileSync(
      path.join(opts.dir, "story.malloy"),
      linearReport(first, second),
   );

   const malloyBytes = readdirSync(opts.dir)
      .filter((f) => f.endsWith(".malloy"))
      .reduce((n, f) => n + statSync(path.join(opts.dir, f)).size, 0);

   const dataDir = path.join(opts.dir, "data");
   if (opts.dataFrom) {
      mkdirSync(dataDir, { recursive: true });
      for (const f of readdirSync(opts.dataFrom)) {
         await Bun.write(
            path.join(dataDir, f),
            Bun.file(path.join(opts.dataFrom, f)),
         );
      }
   } else {
      await writeData(dataDir, rows, seed);
   }

   const exportedSources: string[] = [];
   for (let m = 1; m <= shape.models; m++) {
      for (let s = 1; s <= shape.sourcesPerModel; s++) {
         exportedSources.push(sourceName(m, s));
      }
   }
   return {
      dir: opts.dir,
      preset: opts.preset,
      shape,
      rows,
      seed,
      modelFiles: shape.models + 2,
      sources: shape.models * shape.sourcesPerModel + 3,
      malloyBytes,
      dataBytes: dirBytes(dataDir),
      exportedSources,
      reports: ["overview.malloy", "story.malloy"],
   };
}

if (import.meta.main) {
   const args = process.argv.slice(2);
   const out = args.find((a) => !a.startsWith("--"));
   const flag = (name: string): string | undefined => {
      const i = args.indexOf(`--${name}`);
      return i >= 0 ? args[i + 1] : undefined;
   };
   if (!out) {
      console.error(
         "usage: bun perf/gen-package.ts <out-dir> [--preset small|medium|large] [--rows N] [--seed S]",
      );
      process.exit(2);
   }
   const result = await generatePackage({
      dir: path.resolve(out),
      preset: flag("preset") ?? "small",
      rows: flag("rows") ? Number(flag("rows")) : undefined,
      seed: flag("seed") ? Number(flag("seed")) : undefined,
   });
   console.log(JSON.stringify(result, null, 2));
}
