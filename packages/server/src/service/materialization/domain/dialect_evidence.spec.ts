/**
 * The capability table's evidence (`dialect_evidence.ts`) is complete and
 * honest: every cell that claims more than its safe value has evidence,
 * every probe names a test that exists, each dialect's unverified count is
 * frozen, and the docs table is generated from it.
 *
 * Regenerate the docs table with
 * `UPDATE_DIALECT_EVIDENCE_DOCS=1 bun test dialect_evidence.spec.ts`.
 */

import { describe, expect, it } from "bun:test";
import fs from "fs";
import path from "path";
import {
   CAPABILITIES,
   capabilitiesOf,
   type Capabilities,
   type DialectName,
} from "./dialect";
import { EVIDENCE, SAFE_VALUES, type Evidence } from "./dialect_evidence";

const SERVER_DIR = path.resolve(__dirname, "../../../..");
const DOCS = path.resolve(SERVER_DIR, "../../docs/materialization.md");
const BEGIN =
   "<!-- dialect-evidence:begin (generated by dialect_evidence.spec.ts) -->";
const END = "<!-- dialect-evidence:end -->";

/**
 * Each dialect's count of unverified cells, frozen. A probe that lands lowers
 * one; a count that grows needs a reviewed reason.
 */
const UNVERIFIED_COUNTS: Record<DialectName, number> = {
   duckdb: 0,
   postgres: 0,
   standardsql: 11,
   snowflake: 9,
   databricks: 5,
   trino: 4,
   presto: 3,
   mysql: 2,
   sqlserver: 5,
};

const DIALECTS = Object.keys(CAPABILITIES) as DialectName[];
const CAPABILITY_NAMES = (
   Object.keys(SAFE_VALUES) as (keyof Capabilities)[]
).sort();

const isSafe = (dialect: DialectName, capability: keyof Capabilities) =>
   Bun.deepEquals(CAPABILITIES[dialect][capability], SAFE_VALUES[capability]);

function evidenceOf(
   dialect: DialectName,
   capability: keyof Capabilities,
): Evidence | undefined {
   return EVIDENCE[dialect][capability];
}

/** The names of the `it(...)` tests a spec file declares. */
function testNames(spec: string): Set<string> {
   const text = fs.readFileSync(path.join(SERVER_DIR, spec), "utf8");
   const names = new Set<string>();
   for (const m of text.matchAll(/\bit\(\s*(["'`])((?:(?!\1)[^\\]|\\.)*)\1/g)) {
      names.add(m[2].replace(/\\(.)/g, "$1"));
   }
   return names;
}

describe("the capability table's evidence", () => {
   it("declares a safe value for every capability: the answer for an unknown dialect", () => {
      expect([...CAPABILITY_NAMES]).toEqual(
         (Object.keys(CAPABILITIES.duckdb) as (keyof Capabilities)[]).sort(),
      );
      expect(capabilitiesOf("no_such_dialect")).toEqual(SAFE_VALUES);
      expect(capabilitiesOf(undefined)).toEqual(SAFE_VALUES);
      expect(capabilitiesOf("constructor")).toEqual(SAFE_VALUES);
   });

   it("has evidence for every cell that differs from its safe value", () => {
      const missing: string[] = [];
      for (const dialect of DIALECTS) {
         for (const capability of CAPABILITY_NAMES) {
            if (
               !isSafe(dialect, capability) &&
               !evidenceOf(dialect, capability)
            )
               missing.push(`${dialect}.${capability}`);
         }
      }
      expect(missing).toEqual([]);
   });

   it("names only real capabilities, and marks no safe cell unverified", () => {
      const stray: string[] = [];
      for (const dialect of DIALECTS) {
         for (const [capability, evidence] of Object.entries(
            EVIDENCE[dialect],
         )) {
            const name = capability as keyof Capabilities;
            if (!CAPABILITY_NAMES.includes(name)) {
               stray.push(`${dialect}.${capability}: no such capability`);
            } else if (
               evidence &&
               "unverified" in evidence &&
               isSafe(dialect, name)
            ) {
               stray.push(
                  `${dialect}.${capability}: the safe value needs none`,
               );
            }
         }
      }
      expect(stray).toEqual([]);
   });

   it("names a real test in every probe", () => {
      const unknown: string[] = [];
      const cache = new Map<string, Set<string>>();
      for (const dialect of DIALECTS) {
         for (const [capability, evidence] of Object.entries(
            EVIDENCE[dialect],
         )) {
            if (!evidence || !("probe" in evidence)) continue;
            const at = evidence.probe.indexOf("#");
            const spec = evidence.probe.slice(0, at);
            const test = evidence.probe.slice(at + 1);
            if (at < 0 || !fs.existsSync(path.join(SERVER_DIR, spec))) {
               unknown.push(`${dialect}.${capability}: no spec ${spec}`);
               continue;
            }
            if (!cache.has(spec)) cache.set(spec, testNames(spec));
            if (!cache.get(spec)!.has(test)) {
               unknown.push(`${dialect}.${capability}: no test "${test}"`);
            }
         }
      }
      expect(unknown).toEqual([]);
   });

   it("freezes each dialect's count of unverified cells", () => {
      const counts = Object.fromEntries(
         DIALECTS.map((dialect) => [
            dialect,
            Object.values(EVIDENCE[dialect]).filter(
               (e) => e !== undefined && "unverified" in e,
            ).length,
         ]),
      );
      expect(counts).toEqual(UNVERIFIED_COUNTS);
   });

   it("is the table docs/materialization.md shows", () => {
      const doc = fs.readFileSync(DOCS, "utf8");
      const begin = doc.indexOf(BEGIN);
      const end = doc.indexOf(END);
      expect(begin).toBeGreaterThan(-1);
      expect(end).toBeGreaterThan(begin);
      const table = renderTable();
      if (process.env.UPDATE_DIALECT_EVIDENCE_DOCS === "1") {
         fs.writeFileSync(
            DOCS,
            `${doc.slice(0, begin + BEGIN.length)}\n\n${table}\n\n${doc.slice(end)}`,
         );
         return;
      }
      const shown = doc.slice(begin + BEGIN.length, end);
      expect(normalized(shown)).toEqual(normalized(table));
   });
});

/** A table compared as prettier may lay it out: padding and rule lengths free. */
function normalized(table: string): string[] {
   return table
      .trim()
      .split("\n")
      .map((line) => line.replace(/-{3,}/g, "---").replace(/\s+/g, " ").trim());
}

const typeCount = (n: number) => `${n} type${n === 1 ? "" : "s"}`;

/** One cell's value as the docs show it. */
function shown(value: Capabilities[keyof Capabilities]): string {
   if (value === true) return "yes";
   if (value === false) return "no";
   if (value === undefined) return "none";
   if (typeof value === "number") return String(value);
   if (typeof value === "string") return `\`${value}\``;
   if (Array.isArray(value)) return typeCount(value.length);
   const types = value as {
      malloy: readonly string[];
      native: readonly string[];
   };
   return typeCount(types.malloy.length + types.native.length);
}

/**
 * The capability table as markdown: a row per capability, a column per
 * dialect. A probed cell is bold, an unverified one ends in `?`, and a cell
 * at its safe value with no probe is plain.
 */
function renderTable(): string {
   const header = ["Capability", ...DIALECTS.map((d) => `\`${d}\``)];
   const rows = CAPABILITY_NAMES.map((capability) => [
      `\`${capability}\``,
      ...DIALECTS.map((dialect) => {
         const text = shown(CAPABILITIES[dialect][capability]);
         const evidence = evidenceOf(dialect, capability);
         if (evidence && "probe" in evidence) return `**${text}**`;
         if (evidence && "unverified" in evidence) return `${text}?`;
         return text;
      }),
   ]);
   const widths = header.map((_, i) =>
      Math.max(3, ...[header, ...rows].map((r) => r[i].length)),
   );
   const line = (cells: string[]) =>
      `| ${cells.map((c, i) => c.padEnd(widths[i])).join(" | ")} |`;
   return [
      line(header),
      `| ${widths.map((w) => "-".repeat(w)).join(" | ")} |`,
      ...rows.map(line),
   ].join("\n");
}
