"""Render the -dev variant of a DHI catalog definition from its runtime file.

A DHI image is a pair: a runtime variant (no shell, no package manager, runs as
nonroot) and a -dev variant with a shell and apt, running as root, for build
stages and debugging. The two files differ in a fixed set of fields and are
otherwise identical, so the dev file is generated rather than kept by hand:

    python3 docker/dhi-catalog/render-dev.py \
        docker/dhi-catalog/image/malloy-publisher/debian-13/0.yaml

writes 0-dev.yaml beside it. Plain text rewriting, on purpose: the definition
files carry comments and ordering that a YAML round-trip would lose.
"""
import re
import sys
from pathlib import Path

DEV_PACKAGES = """    - apt
    - base-files
    - bash
    - ca-certificates
    - coreutils
    - diffutils
    - dpkg
    - findutils
    - grep
    - libc-bin
    - libstdc++6
    - mawk
    - perl-base
    - sed
    - util-linux
"""


def render(src: str) -> str:
    out = src
    out = out.replace("\nname: Malloy Publisher 0.x\n", "\nname: Malloy Publisher 0.x (dev)\n")
    out = out.replace("\nvariant: runtime\n", "\nvariant: dev\n")
    # Every tag gets a -dev suffix.
    out = re.sub(r'(?m)^(  - )("?)([0-9][^"\n]*)("?)$', r"\1\2\3-dev\4", out.split("\nplatforms:")[0]) + "\nplatforms:" + out.split("\nplatforms:", 1)[1]
    # The runtime's own package list becomes the dev list plus what the
    # runtime adds (git and its two explicit libraries), keeping the exclusions.
    m = re.search(r"(?ms)^  packages:\n(.*?)(?=^  builds:)", out)
    assert m, "runtime packages block not found"
    block = m.group(1)
    excl = "".join(l + "\n" for l in block.splitlines() if l.strip().startswith("- '!"))
    extra = "".join(l + "\n" for l in block.splitlines()
                    if l.strip().startswith("- ") and not l.strip().startswith("- '!")
                    and l.strip()[2:] not in {"base-files", "ca-certificates", "coreutils", "libstdc++6"})
    out = out[: m.start(1)] + excl.replace("    - '!mawk'\n", "") + DEV_PACKAGES + extra + out[m.end(1):]
    out = out.replace("accounts:\n  run-as: nonroot\n", "accounts:\n  root: true\n  run-as: root\n")
    out = out.replace("""    - name: nonroot
      uid: 65532
      gid: 65532
  groups:""", """    - name: nonroot
      uid: 65532
      gid: 65532
    - name: _apt
      uid: 42
      gid: 65532
  groups:""")
    out = re.sub(r"(?ms)^environment:\n", "environment:\n  DEBIAN_FRONTEND: noninteractive\n", out, count=1)
    out = re.sub(r"(?ms)^cmd:\n(  - .*\n)+", "cmd:\n  - /bin/bash\n", out, count=1)
    header = ("# GENERATED by docker/dhi-catalog/render-dev.py from 0.yaml; edit that file.\n")
    return out.replace("# syntax=dhi.io/build:2-debian13\n", "# syntax=dhi.io/build:2-debian13\n" + header, 1)


def main() -> None:
    src = Path(sys.argv[1])
    dst = src.with_name(src.stem + "-dev.yaml")
    dst.write_text(render(src.read_text()))
    print(f"wrote {dst}")


if __name__ == "__main__":
    main()
